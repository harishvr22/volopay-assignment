import JSZip from 'jszip';
import Papa from 'papaparse';
import { ManifestEntry, ProcessedRecord } from '../types';
import { EVIDENCE_FINDINGS, REJECTED_DECISION } from './findingsData';
import { MANAGER_BRIEF_2026_08_21 } from './managerBriefData';

export interface GeneratedExportArchive {
  zipBlob: Blob;
  manifestEntries: ManifestEntry[];
  validationResult: {
    isValid: boolean;
    totalFiles: number;
    manifestPathCount: number;
    missingPaths: string[];
    errors: string[];
  };
}

/**
 * Generate manifest entries for all current records.
 * Follows DATA_CONTRACT.md section 3 & 3.H rules.
 */
export function generateManifestEntries(records: ProcessedRecord[]): ManifestEntry[] {
  return records.map((record) => {
    const isOverride = !!record.manual_override;
    const routesStr = record.active_routes.join(', ');

    // Output paths inside the archive
    const recordPath = `records/${record.source_type}_${record.source_id}.json`;
    const paths: string[] = [recordPath];

    if (record.hasUsableText && record.analysis) {
      paths.push(`analysis/${record.record_ref}_analysis.md`);
    }

    return {
      source_type: record.source_type,
      source_id: record.source_id,
      record_ref: record.record_ref,
      applied_source_revision: record.applied_source_revision,
      routes: routesStr,
      output_paths: paths.join('; '),
      processing_review_state: record.review_state,
      manual_override_flag: isOverride,
      analysis_freshness: record.analysis_freshness,
      source_revision_analysed: record.analysis ? record.analysis.sourceRevisionAnalysed : null,
    };
  });
}

/**
 * Generates routing summary rows for CSV export.
 */
export function generateRoutingSummaryCsv(records: ProcessedRecord[]): string {
  const rows = records.map((r) => ({
    record_ref: r.record_ref,
    source_type: r.source_type,
    source_id: r.source_id,
    applied_revision: r.applied_source_revision,
    person: r.personLabel,
    person_role: r.personRole,
    usable_text: r.hasUsableText ? 'Yes' : 'No',
    active_routes: r.active_routes.join('; '),
    suggested_routes: r.suggested_routes.join('; '),
    is_manual_override: !!r.manual_override ? 'TRUE' : 'FALSE',
    manual_override_reason: r.manual_override?.reason || '',
    review_state: r.review_state,
    analysis_freshness: r.analysis_freshness,
  }));

  return Papa.unparse(rows);
}

/**
 * Formats Markdown analysis for a single conversation.
 */
export function formatConversationAnalysisMarkdown(record: ProcessedRecord): string {
  const a = record.analysis;
  if (!a) {
    return `# Record Analysis: ${record.record_ref}
**Source Type**: ${record.source_type}
**Source ID**: ${record.source_id}
**Review State**: ${record.review_state}

*No usable conversation text was supplied for this record. Per data contract rules, zero substantive analysis has been inferred.*
`;
  }

  const citationsMd = a.citations
    .map(
      (c) =>
        `- **Passage (${c.reference})**: "${c.quoteOrTurn}"\n  *Context*: ${c.context || 'Supporting evidence'}`
    )
    .join('\n');

  const stepsMd = a.supportedNextSteps.map((s) => `- ${s}`).join('\n');
  const uncertaintiesMd = a.uncertainties.map((u) => `- ${u}`).join('\n');

  return `# Revenue Intelligence Analysis: ${record.record_ref}
- **Source Type**: ${record.source_type.toUpperCase()}
- **Source ID**: \`${record.source_id}\`
- **Applied Source Revision**: ${record.applied_source_revision}
- **Analysed Source Revision**: ${a.sourceRevisionAnalysed}
- **Analysis Freshness**: ${a.freshness.toUpperCase()}
- **Active Routes**: ${record.active_routes.join(', ')}
- **Manual Override Active**: ${record.manual_override ? 'YES' : 'NO'}
- **Identified Owner**: ${a.owner || 'Unassigned in source'} ${a.ownerRationale ? `(${a.ownerRationale})` : ''}

---

## 1. What Happened
${a.whatHappened}

## 2. Why It Matters
${a.whyItMatters}

## 3. Supported Next Steps
${stepsMd}

## 4. Supporting Transcript Evidence
${citationsMd}

## 5. Uncertainties & Evidence Boundaries
${uncertaintiesMd}

---
*Generated by SpendNest Revenue Intelligence Engine. ${a.generationNote}*
`;
}

/**
 * Formats the Manager Brief in Markdown.
 */
export function formatManagerBriefMarkdown(): string {
  const brief = MANAGER_BRIEF_2026_08_21;
  const sectionsMd = brief.sections
    .map((s) => {
      const contentMd = s.content.map((c) => `- ${c}`).join('\n');
      const refsMd = s.traceableReferences
        ? `\n**Traceable Source Citations**:\n` +
          s.traceableReferences.map((r) => `  * [${r.ref}] ${r.note}`).join('\n')
        : '';
      return `### ${s.title} [${s.badge || 'Section'}]\n${contentMd}\n${refsMd}\n`;
    })
    .join('\n---\n\n');

  return `# SpendNest Executive Manager Brief
**Date of Selected Activity**: ${brief.briefDate} (${brief.timezone})
**Delivery Timestamp**: ${brief.generatedAt}
**Engine Status**: Pre-generated synthesis of all 18 usable post-update conversations

> **Transparency Disclosure**: ${brief.disclosureNote}

---

${sectionsMd}
`;
}

/**
 * Builds the complete export ZIP archive with all required folders and files.
 * Validates that every active path listed in the manifest exists in the ZIP archive.
 */
export async function buildCompleteExportArchive(
  records: ProcessedRecord[]
): Promise<GeneratedExportArchive> {
  const zip = new JSZip();
  const manifestEntries = generateManifestEntries(records);

  // 1. Manifest JSON & CSV
  const manifestJsonStr = JSON.stringify(manifestEntries, null, 2);
  const manifestCsvStr = Papa.unparse(manifestEntries);
  zip.file('manifest.json', manifestJsonStr);
  zip.file('manifest.csv', manifestCsvStr);

  // 2. Routing summary CSV
  const routingSummaryCsv = generateRoutingSummaryCsv(records);
  zip.file('routing_summary.csv', routingSummaryCsv);

  // 3. Findings JSON
  const findingsJsonStr = JSON.stringify(
    {
      evidence_findings: EVIDENCE_FINDINGS,
      rejected_decision: REJECTED_DECISION,
      timestamp: new Date().toISOString(),
    },
    null,
    2
  );
  zip.file('findings.json', findingsJsonStr);

  // 4. Brief Markdown
  const briefMd = formatManagerBriefMarkdown();
  zip.file('brief/manager_brief_2026-08-21.md', briefMd);

  // 5. Records JSON folder (all 44 records)
  const recordsFolder = zip.folder('records')!;
  for (const r of records) {
    const filename = `${r.source_type}_${r.source_id}.json`;
    recordsFolder.file(filename, JSON.stringify(r, null, 2));
  }

  // 6. Analysis Markdown folder (all usable conversations)
  const analysisFolder = zip.folder('analysis')!;
  for (const r of records) {
    if (r.hasUsableText && r.analysis) {
      const filename = `${r.record_ref}_analysis.md`;
      analysisFolder.file(filename, formatConversationAnalysisMarkdown(r));
    }
  }

  // --- PATH VALIDATION ---
  // Verify that every single relative output path listed in the manifest exists in the archive!
  const errors: string[] = [];
  const missingPaths: string[] = [];
  let manifestPathCount = 0;

  for (const entry of manifestEntries) {
    const relativePaths = entry.output_paths.split(';').map((p) => p.trim());
    for (const relPath of relativePaths) {
      if (!relPath) continue;
      manifestPathCount++;
      const fileInZip = zip.file(relPath);
      if (!fileInZip) {
        missingPaths.push(relPath);
        errors.push(
          `Manifest entry for ${entry.record_ref} references missing archive path: "${relPath}"`
        );
      }
    }
  }

  // Count total files in zip
  let totalFiles = 0;
  zip.forEach(() => {
    totalFiles++;
  });

  const isValid = missingPaths.length === 0;

  const zipBlob = await zip.generateAsync({
    type: 'blob',
    compression: 'DEFLATE',
    compressionOptions: { level: 6 },
  });

  return {
    zipBlob,
    manifestEntries,
    validationResult: {
      isValid,
      totalFiles,
      manifestPathCount,
      missingPaths,
      errors,
    },
  };
}

/**
 * Trigger browser file download helper.
 */
export function triggerFileDownload(blob: Blob, filename: string): void {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
